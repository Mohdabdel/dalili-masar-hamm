export interface ParticipationLevels {
  guided: string;
  shared: string;
  independent: string;
}

export interface FullCard {
  title: string;
  description?: string;
  whyParticipate: string;
  setup: string;
  steps: string[];
  support: string;
  levels: ParticipationLevels;
  progressIndicators: string[];
  teachingAids?: string[];
  nextStep: string;
  expectedMinutes?: number;
  needsOutside?: boolean;
  needsTools?: boolean;
  keywords?: string[];
}


export interface Opportunity {
  id: string;
  name: string;
  levels?: ParticipationLevels;
  card?: FullCard;
}

export interface LifeEvent {
  id: string;
  name: string;
  opportunities: Opportunity[];
}

export interface GeneralActivity {
  id: string;
  name: string;
  events: LifeEvent[];
}

export interface HomeDomain {
  id: string;
  name: string;
  activities: GeneralActivity[];
}

const oppCard = (id: string, card: FullCard): Opportunity => ({
  id,
  name: card.title,
  levels: card.levels,
  card,
});

const opp = (id: string, name: string): Opportunity => ({ id, name });

